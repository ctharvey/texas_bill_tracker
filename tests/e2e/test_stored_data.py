def test_disclaimer_is_not_shown_again(saved_device):
    page = saved_device.open("#all")
    assert page.evaluate("document.getElementById('disclaimer').open") is False
    assert saved_device.storage()["tx-bill-atlas-disclaimer-v1"] == LOCAL["tx-bill-atlas-disclaimer-v1"]


def test_stored_sync_link_is_recognized(saved_device):
    page = saved_device.open("#watchlist")
    expect(page.locator("#sync-copy-edit")).to_be_visible()
    expect(page.locator("#sync-create")).to_have_count(0)
    expect(page.get_by_text("This device is synced; changes save automatically.")).to_be_visible()
    link = json.loads(saved_device.storage()[SYNC_KEY])
    assert link["key"] == STATE["sync"]["edit_key"] and link["mode"] == "edit"
    assert link["viewKey"] == STATE["sync"]["view_key"]
    assert "sync=" not in page.url  # the edit key never reaches the address bar
    assert STATE["sync"]["edit_key"] not in page.url


def test_stored_sync_database_serves_the_stored_list(saved_device):
    # The stored database is readable by today's service, with the stored edit key: same list, follows and searches.
    page = saved_device.open("#watchlist")
    reply = page.request.get(saved_device.site.base + "api/sync", headers={"X-Sync-Key": STATE["sync"]["edit_key"]})
    assert reply.status == 200
    body = reply.json()
    assert body["mode"] == "edit"
    assert body["data"]["watch"] == STATE["watch"]
    assert body["data"]["follows"] == STATE["follows"]
    assert body["data"]["searches"] == STATE["searches"]
    view = page.request.get(saved_device.site.base + "api/sync", headers={"X-Sync-Key": STATE["sync"]["view_key"]}).json()
    assert view["mode"] == "view" and view["data"]["watch"] == STATE["watch"] and "follows" not in view["data"]


def test_a_device_with_only_the_sync_link_gets_the_list_from_the_server(device_factory, stored_sync):
    # Another phone that has just the stored link (no list of its own): everything must come from the stored database.
    device = device_factory(accept_disclaimer=False)
    inject(device, {SYNC_KEY: LOCAL[SYNC_KEY], "tx-bill-atlas-disclaimer-v1": LOCAL["tx-bill-atlas-disclaimer-v1"]})
    page = device.open("#watchlist")
    expect(page.locator("#nav-watch")).to_have_text(str(len(STATE["watch"])))
    expect(page.locator("#nav-follow")).to_have_text(str(len(STATE["follows"]) + len(STATE["searches"])))
    for bill in STATE["watch"]:
        expect(page.locator(f"#bill-list [data-watch='{bill}']")).to_have_attribute("aria-pressed", "true")
    stored = device.storage()
    assert json.loads(stored["tx-bill-atlas-watch-90r"]) == STATE["watch"]
    assert json.loads(stored["tx-bill-atlas-follow-90r"]) == STATE["follows"]
    assert json.loads(stored["tx-bill-atlas-searches-90r"]) == STATE["searches"]
    page = device.open("#following")
    assert page.locator(".saved-search-name").all_inner_texts() == [s["name"] for s in STATE["searches"]]


def test_lists_load_from_this_browsers_own_storage_alone(device_factory, fresh_sync):
    """No sync link and an empty server: the watchlist, follows and saved searches can only come from the stored
    localStorage keys themselves. This is the test that fails if the watch, follow or searches key were renamed (the
    sync-backed tests above could be masked by the server's copy)."""
    device = device_factory(accept_disclaimer=False)
    inject(device, {k: v for k, v in LOCAL.items() if k != SYNC_KEY})
    page = device.open("#watchlist")
    expect(page.locator("#nav-watch")).to_have_text(str(len(STATE["watch"])))
    for bill in STATE["watch"]:
        expect(page.locator(f"#bill-list [data-watch='{bill}']")).to_have_attribute("aria-pressed", "true")
    expect(page.locator("#sync-create")).to_be_visible()  # no link: offers to create one
    page = device.open("#following")
    expect(page.locator(".followed-member")).to_have_count(len(STATE["follows"]))
    assert page.locator(".saved-search-name").all_inner_texts() == [s["name"] for s in STATE["searches"]]


def test_loading_does_not_rewrite_stored_values(saved_device):
    """Visiting every saving-related view must leave each stored key exactly as it was: same keys, same JSON values.

    Today the app rewrites nothing on load that changes meaning (it re-saves the watchlist, follows, searches and
    remembered filters with the same content, and the sync link state with the same version). A renamed key shows up
    as a missing original and an extra new key; a reshaped value as a differing value."""
    for view in ("#all", "#watchlist", "#following", "#local", "#saving"):
        saved_device.open(view)
    now = saved_device.storage()
    assert sorted(now) == sorted(LOCAL), f"keys changed: {sorted(set(now) ^ set(LOCAL))}"
    for key, value in LOCAL.items():
        if key == "tx-bill-atlas-disclaimer-v1":
            assert now[key] == value  # a timestamp, never rewritten once seen
        elif key == "tx-bill-atlas-prefs-v1":
            # A filter added after the capture (e.g. party) is re-saved at its empty default; captured ones keep theirs.
            old, new = json.loads(value), json.loads(now[key])
            assert set(new) == set(old), key
            added = set(new["filters"]) - set(old["filters"])
            assert {k: new["filters"][k] for k in old["filters"]} == old["filters"], key
            assert all(new["filters"][k] in ("", False) for k in added), (key, added)
        else:
            assert json.loads(now[key]) == json.loads(value), key
    assert saved_device.page.evaluate("document.getElementById('disclaimer').open") is False


# ---- Files: import into a fresh profile ----

def import_file(device, path: Path):
    page = device.open("#watchlist")
    page.set_input_files("#import-watch-file", str(path))
    return page


def test_profile_file_imports_into_a_fresh_profile(device):
    page = import_file(device, STORED / "profile-file.json")
    n_watch, n_follow, n_search = len(STATE["watch"]), len(STATE["follows"]), len(STATE["searches"])
    expect(page.locator("#toast")).to_have_text(
        f"Added {n_watch} of {n_watch} bills, {n_follow} of {n_follow} legislators, {n_search} of {n_search} saved searches")
    expect(page.locator("#nav-watch")).to_have_text(str(n_watch))
    expect(page.locator("#nav-follow")).to_have_text(str(n_follow + n_search))
    for bill in STATE["watch"]:
        expect(page.locator(f"#bill-list [data-watch='{bill}']")).to_have_attribute("aria-pressed", "true")
    stored = device.storage()
    assert json.loads(stored["tx-bill-atlas-watch-90r"]) == STATE["watch"]
    assert json.loads(stored["tx-bill-atlas-follow-90r"]) == STATE["follows"]
    assert json.loads(stored["tx-bill-atlas-searches-90r"]) == STATE["searches"]  # names (incl. rename), filters, seen
    page = device.open("#following")
    assert page.locator(".saved-search-name").all_inner_texts() == [s["name"] for s in STATE["searches"]]
    for name in STATE["followed_names_shown"]:
        expect(page.locator(".followed-members")).to_contain_text(name)


def test_exporting_the_imported_profile_gives_the_same_file(device):
    # Round trip: what the UI exports now has the format and content of the stored export.
    page = import_file(device, STORED / "profile-file.json")
    expect(page.locator("#nav-watch")).to_have_text(str(len(STATE["watch"])))
    with page.expect_download() as download:
        page.click("#export-watch")
    assert download.value.suggested_filename == STATE["profile_download_name"]
    out = json.loads(Path(download.value.path()).read_text("utf-8"))
    expected = json.loads((STORED / "profile-file.json").read_text("utf-8"))
    assert re.fullmatch(r"\d{4}-\d\d-\d\dT[\d:.]+Z", out.pop("exported_at"))
    expected.pop("exported_at")
    assert out == expected


def test_older_watchlist_file_imports_into_a_fresh_profile(device):
    page = import_file(device, STORED / "watchlist-file.json")
    n = len(STATE["watch"])
    expect(page.locator("#toast")).to_have_text(f"Added {n} of {n} bills")
    expect(page.locator("#nav-watch")).to_have_text(str(n))
    stored = device.storage()
    assert json.loads(stored["tx-bill-atlas-watch-90r"]) == STATE["watch"]
    assert "tx-bill-atlas-follow-90r" not in stored or json.loads(stored["tx-bill-atlas-follow-90r"]) == []
    expect(page.locator("#result-count")).to_have_text(f"{n} bills")
